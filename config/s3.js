import { S3Client, HeadObjectCommand, DeleteObjectCommand, GetObjectCommand } from "@aws-sdk/client-s3";
import { createPresignedPost } from "@aws-sdk/s3-presigned-post";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";
import crypto from "crypto";

export const MAX_IMAGE_BYTES = 5 * 1024 * 1024;
export const ALLOWED_IMAGE_TYPES = ["image/jpeg", "image/png", "image/webp"];

const UPLOAD_EXPIRES_SECONDS = 5 * 60;
const READ_EXPIRES_SECONDS = 60 * 60;

let client;

function getClient() {
    if (!client) {
        client = new S3Client({ region: process.env.AWS_REGION });
    }
    return client;
}

function getBucket() {
    const bucket = process.env.S3_BUCKET;
    if (!bucket) {
        throw new Error("S3_BUCKET is not configured");
    }
    return bucket;
}

const EXTENSIONS = {
    "image/jpeg": "jpg",
    "image/png": "png",
    "image/webp": "webp",
};

// Object keys are generated by the server and always scoped to the owner and todo.
export function todoImagePrefix(userID, todoId) {
    return `todos/${userID}/${todoId}/`;
}

export function buildTodoImageKey(userID, todoId, contentType) {
    const ext = EXTENSIONS[contentType];
    return `${todoImagePrefix(userID, todoId)}${crypto.randomUUID()}.${ext}`;
}

// Presigned POST: S3 itself enforces the content type and the size range.
export async function createImageUploadPost(key, contentType) {
    return createPresignedPost(getClient(), {
        Bucket: getBucket(),
        Key: key,
        Conditions: [
            ["content-length-range", 1, MAX_IMAGE_BYTES],
            ["eq", "$Content-Type", contentType],
        ],
        Fields: {
            "Content-Type": contentType,
        },
        Expires: UPLOAD_EXPIRES_SECONDS,
    });
}

// Returns { ContentLength, ContentType } for an existing object, or null if it does not exist.
export async function headImage(key) {
    try {
        const result = await getClient().send(
            new HeadObjectCommand({ Bucket: getBucket(), Key: key })
        );
        return { contentLength: result.ContentLength, contentType: result.ContentType };
    } catch (error) {
        if (error.name === "NotFound" || error.$metadata?.httpStatusCode === 404) {
            return null;
        }
        throw error;
    }
}

export async function deleteImage(key) {
    if (!key) return;
    await getClient().send(new DeleteObjectCommand({ Bucket: getBucket(), Key: key }));
}

export function createImageReadUrl(key) {
    return getSignedUrl(
        getClient(),
        new GetObjectCommand({ Bucket: getBucket(), Key: key }),
        { expiresIn: READ_EXPIRES_SECONDS }
    );
}
